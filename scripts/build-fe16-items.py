"""
Builds src/data/fe16/fe16Weapons.ts: Three Houses' weapons, read from the game's own item table (fixed_data.bin section 0,
scripts/fe16_data.py) and named from its English text. Run:
    python scripts/build-fe16-items.py

The record's fields are in data-raw/fe16/README.md. What they do was read in the game's code: effectiveness triples Mt (`0xd99a0`,
the weapon's +14 against the defender's class type bits), a crit triples damage (`0xdc1ec`); the rest (strikes twice, magic, against
Res, no follow-up, leaves 1 HP) are the record's flags as the Three Houses Research Team's templates name them.
Left out: Unarmed, the five broken weapons (what a weapon at 0 uses fights as, never an item of its own), the blank records, and
weapons no table names. Spells aren't items: each unit learns them, so they're the Unit Planner's.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fe16_data as D  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fe16', 'fe16Weapons.ts')
CATEGORIES = ['Sword', 'Lance', 'Axe', 'Bow', 'Gauntlets']
RANKS = ['E', 'D', 'C', 'B', 'A', 'S']
# Effectiveness bits (+14) -> the weapon page's targets; bit 0 (infantry) no weapon sets.
TARGETS = [(2, 'armour'), (4, 'horseback'), (8, 'flying'), (16, 'dragon'), (32, 'monster')]
CRESTS = {}


def crest_name(c):
    """A crest's name, from the text's crest list (found by the Crest of Seiros, crest 2)."""
    if not CRESTS:
        t = D.texts()[1]
        base = t.index('Crest of Seiros') - 2
        for k in range(0, 86):
            CRESTS[k] = t[base + k]
    return CRESTS.get(c)


def weapon_range(w):
    lo, hi = w['min_range'], w['max_range']
    if hi >= 100:
        # The Creator swords' max range byte is 150; the game shows 1-2 (Fire Emblem Wiki: 2 for Byleth only); not traced in the code.
        hi = 2
    return str(lo) if lo == hi else f'{lo}-{hi}'


def rules_of(w):
    out = []
    f = w['flags']
    if f & 0x20:
        out.append('Strikes twice when it attacks')
    if f & 0x02:
        out.append("Fought against the foe's Res")
    if f & 0x10:
        out.append('No follow-up attack')
    if f & 0x04:
        out.append('Leaves the foe at 1 HP')
    if w['crest'] != 86 and crest_name(w['crest']):
        out.append(f"Linked to the {crest_name(w['crest'])}")
    if w['status'] == 6:
        out.append('Poisons the foe')
    return out


def main():
    out = []
    for w in D.weapons():
        n = w['id']
        name = w['name']
        if not name or n < 6 or w['flags1'] & 0x40:
            continue  # Unarmed, the broken weapons, blank records
        stone = bool(w['flags1'] & 0x80) or w['raw'][0] == 0
        if not stone and w['type'] > 4:
            continue
        cat = 'Monster' if stone else CATEGORIES[w['type']]
        rank = '' if stone else RANKS[w['rank']] if w['rank'] < len(RANKS) else str(w['rank'])
        e = {
            'id': f'fe16-{n}', 'name': name, 'romId': n, 'category': cat, 'rank': rank, 'range': weapon_range(w),
            'mt': w['mt'], 'hit': w['hit'], 'crit': w['crit'], 'wt': w['wt'], 'uses': w['uses'],
            'effective': [key for bit, key in TARGETS if w['effective'] & bit], 'rules': rules_of(w),
        }
        if w['flags'] & 0x01:
            e['magic'] = True
        out.append(e)
    # Two weapons named alike get their record number (the game shows them the same).
    seen = {}
    for e in out:
        seen.setdefault(e['name'], []).append(e)
    for name, es in seen.items():
        if len(es) > 1:
            for e in es[1:]:
                e['name'] = f"{name} ({e['romId']})"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    lines = [
        "import type { ChapterWeapon } from '../../components/ChapterWeapons'",
        '',
        '/*',
        " * GENERATED by scripts/build-fe16-items.py from Three Houses' own item table (fixed_data.bin), named from its English text.",
        ' * Do not edit by hand.',
        ' */',
        'export const FE16_WEAPONS: ChapterWeapon[] = [',
    ]
    lines += ['  ' + json.dumps(e, ensure_ascii=False) + ',' for e in out]
    lines.append(']')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', len(out), 'weapons')


if __name__ == '__main__':
    main()
