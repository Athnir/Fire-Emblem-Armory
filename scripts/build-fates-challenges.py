"""
Builds src/data/maps/fatesChallenges.ts: Fates' challenge battles (the scouted reruns of a chapter's or paralogue's map).

A challenge is fought on the base map with everything in it spent (every Dragon Vein used, every wall broken, every door and
chest open: read live in Chapter 3's, where the veins' bridges were down), with an encounter placement file, <code>E
(A002E-A026E, C006E-C026E, X001E-X022E; Conquest has none). The file's Player group is the start tiles (all open slots); Mob00
and Mob01 are the two foe groups, every slot blank (PID_無し: the game picks the units).

Each group is an encounter of its own (0x4187cc): a new one goes to a free group, either one when both are (a coin flip), so a
battle with one boss has either group and a dual-boss battle both. How many foes a group fields, its boss included (0x417b98,
from the group's seed): one per slot on Lunatic, two fewer on Normal and Hard (three from 16 slots), then rand(n / 3 + 1)
fewer. Placing them (0x39ef4c, from the same seed): the boss on the group's first slot, the other slots shuffled
(slot i swaps with 1 + rand(n - 1)), then each foe in turn on the next slot; a foe is paired (50% the boss, 25% the others,
while two or more are left) with the next one, which skips its slot. All four battles read live in Chapter 3's challenge
matched this to the tile. The two shiny spots are the terrain script's trick kind 14 (the tile check at 0x369518 looks for
kinds 13 and 14): fixed tiles, the same in every battle on the map.

Needs the dumped game files in data-raw/fates/romfs/ (git-ignored). Run:
    python scripts/build-fates-challenges.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fates_dispos import read as read_dispos  # noqa: E402
from fates_maps import MAPS, ROOT, find, terrain, terrain_script  # noqa: E402
from fates_terrain import read as read_terrain  # noqa: E402
from fates_tricks import tricks as read_tricks  # noqa: E402

OUT = os.path.join(ROOT, 'src', 'data', 'maps', 'fatesChallenges.ts')
SHINY = 14
# The routes with challenge battles (Conquest has none).
CHALLENGE_ROUTES = ['Birthright', 'Revelation']
PARALOGUE_ROUTES = {n: ['Birthright', 'Conquest', 'Revelation'] if n <= 6 else
                    ['Birthright', 'Revelation'] if n <= 14 else ['Conquest', 'Revelation'] for n in range(1, 23)}


def main():
    out = {}
    for map_id, (code, route, chapter) in MAPS.items():
        if route not in ('Shared', 'Birthright', 'Revelation', 'Paralogue'):
            continue
        path = find('Dispos', code + 'E')
        if not path:
            continue
        t = read_terrain(terrain(code))
        H = t['h'] - 2
        groups = {g['name']: [u['start'] for u in g['units']] for g in read_dispos(path, H)}
        assert set(groups) == {'Player', 'Mob00', 'Mob01'}, (code, list(groups))
        spots = [(x, H + 1 - y) for x, y, w, h, k in read_tricks(terrain_script(code)) if k == SHINY]
        assert len(spots) == 2, (code, spots)
        if route == 'Paralogue':
            routes = [r for r in PARALOGUE_ROUTES[chapter] if r in CHALLENGE_ROUTES]
        elif route == 'Shared':
            routes = CHALLENGE_ROUTES
        else:
            routes = [route]
        out[map_id] = {
            'code': code + 'E',
            'availableIn': routes,
            'starts': groups['Player'],
            'groups': [{'boss': groups[g][0], 'foes': groups[g][1:]} for g in ('Mob00', 'Mob01')],
            'spots': sorted(spots),
        }
    tile = lambda t: f'[{t[0]}, {t[1]}]'  # noqa: E731
    lines = [
        '/*',
        " * GENERATED by scripts/build-fates-challenges.py from the game's encounter placement files (<code>E) and terrain",
        ' * scripts. Do not edit by hand.',
        ' */',
        "import type { Tile } from './types'",
        '',
        "/** A challenge foe group: its boss's tile and its other slots' tiles, in the file's order (a battle fills them in a random order). */",
        'export interface ChallengeGroup {',
        '  boss: Tile',
        '  foes: Tile[]',
        '}',
        '',
        '/** A challenge battle on a chapter\'s or paralogue\'s map, keyed by that map\'s id. */',
        'export interface GameChallenge {',
        "  /** The game's encounter placement file. */",
        '  code: string',
        "  /** The routes it can be scouted on (Conquest has no challenges). */",
        "  availableIn: ('Birthright' | 'Revelation')[]",
        '  /** Where your units start: open slots. */',
        '  starts: Tile[]',
        '  /** The two groups: a battle has one, either one, or both in a dual-boss battle. */',
        '  groups: [ChallengeGroup, ChallengeGroup]',
        "  /** The two shiny spots. */",
        '  spots: Tile[]',
        '}',
        '',
        'export const FATES_CHALLENGES: Record<string, GameChallenge> = {',
    ]
    for map_id, c in out.items():
        groups = ', '.join('{ boss: ' + tile(g['boss']) + ', foes: [' + ', '.join(tile(t) for t in g['foes']) + '] }' for g in c['groups'])
        lines.append(f"  '{map_id}': {{ code: '{c['code']}', availableIn: {json.dumps(c['availableIn'])}, "
                     f"starts: [{', '.join(tile(t) for t in c['starts'])}], groups: [{groups}], spots: [{', '.join(tile(t) for t in c['spots'])}] }},")
    lines.append('}')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('wrote', OUT, len(out), 'challenge maps')


if __name__ == '__main__':
    main()
