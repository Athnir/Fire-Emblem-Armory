"""
Builds src/data/fe4/fe4Bonuses.ts: Genealogy of the Holy War's weapon triangle and leadership, read from the battle code in the
user's ROM (scripts/fe4_rom.py), for the weapon triangle tab. The game has no support levels; the Charisma and lover bonuses the same
routine adds are a unit's own, so they're left to the Unit Planner (they're described below and in data-raw/fe4/README.md). Run:
    python scripts/build-fe4-bonuses.py

The code (65816, bank $84; disassemble with scripts/fe4_asm.py):
  - $84:DB52 sums the bonus a unit gets from the units around it. It walks every unit on the map; one of the same army at a
    distance of 1 to 3 tiles (|dx| + |dy|, the CMP #$04 at $84:DB92) adds: +10 if it has Charisma (skill 0x0C, $84:DBDC); +10 if it
    is the unit's lover ($84:DBEF); its leadership bonus if it is the unit's commander ($84:DC00: a table by stars at $84:DC0D).
  - $84:D97B adds the lord's own leadership (Sigurd and Seliph, by character id 1 and 0x19, or a unit with leader bit 0x100), from the
    same table at $84:D9B0.
  - $84:D956 adds the sum to both accuracy (+0x34) and avoid (+0x36).
  - $84:D91E adds the weapon triangle's bonus (+20, $84:FB32) to both accuracy and avoid of the side whose weapon has the advantage:
    the table at $84:FB37 lists, for each defending weapon type, the attacking types that beat it.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fe4_rom import R, u16  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fe4', 'fe4Bonuses.ts')
TYPES = ['Sword', 'Lance', 'Axe', 'Bow', 'Staff', 'Fire', 'Thunder', 'Wind', 'Light', 'Dark']


def imm(snes, opcode):
    """The 16-bit immediate operand of the instruction at a bank $84 address, checked to be the expected opcode."""
    o = 0x40000 + snes
    assert R[o] == opcode, (hex(snes), hex(R[o]))
    return u16(o + 1)


def main():
    leadership = list(R[0x4DC0D:0x4DC13])
    assert leadership == list(R[0x4D9B0:0x4D9B6]), 'the lord uses the same table'
    charisma = imm(0xDBDC, 0xA9)      # LDA #$000A
    lover = imm(0xDBEF, 0xA9)
    triangle = imm(0xFB32, 0xA9)       # LDA #$0014
    reach = imm(0xDB92, 0xC9) - 1      # CMP #$0004: 4 tiles or more don't count
    beats = {}
    base = 0x4FB37
    for defender in range(len(TYPES)):
        o = base + u16(base + 2 * defender)
        while R[o] != 0xFF:
            beats.setdefault(TYPES[R[o]], []).append(TYPES[defender])
            o += 1
    beats = {t: beats[t] for t in TYPES if t in beats}  # in the item table's type order
    assert (charisma, lover) == (10, 10), 'the README says +10 each'
    data = {'leadership': leadership, 'triangle': triangle, 'reach': reach, 'beats': beats}
    lines = [
        '/*',
        " * GENERATED by scripts/build-fe4-bonuses.py from Genealogy of the Holy War's battle code. Do not edit by hand.",
        ' */',
        '',
        '/** The bonuses to accuracy and avoid (both get the same), and which weapon types beat which. `leadership` is by stars, 0-5;',
        ' * `reach` is how far (in steps) the commander can be for theirs to count. */',
        f'export const FE4_BONUSES = {json.dumps(data, indent=2)} as const',
    ]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(data)


if __name__ == '__main__':
    main()
