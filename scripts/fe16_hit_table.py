"""
Writes src/logic/fe16HitTable.ts: Three Houses' true hit for each displayed hit, counted over every state of the battle's random
number generator. Run (about two minutes; needs numpy):
    python scripts/fe16_hit_table.py

The hit roll (`0x5bb8a0`, data-raw/fe16/README.md) steps an LCG (x = x * 1103515245 + 12345, 32 bits) twice and takes each number as
(x >> 16) mod 100; it hits when their average, rounded down, is below the displayed hit. Every 32-bit state comes up once in the
generator's period, so the share of states whose next two numbers hit is the true hit, exactly: the table holds it in basis points
(hundredths of a percent), rounded.
"""
import os

import numpy as np

A, C = 1103515245, 12345
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'logic', 'fe16HitTable.ts')


def main():
    hist = np.zeros(100, dtype=np.int64)
    chunk = 1 << 24
    for k in range(1 << 8):
        x = np.arange(k * chunk, (k + 1) * chunk, dtype=np.uint64)
        x1 = (x * A + C) & 0xFFFFFFFF
        x2 = (x1 * A + C) & 0xFFFFFFFF
        avg = (((x1 >> 16) % 100) + ((x2 >> 16) % 100)) >> 1
        hist += np.bincount(avg.astype(np.int64), minlength=100)
    assert hist.sum() == 1 << 32
    cum = np.concatenate([[0], np.cumsum(hist)])
    table = [int(round(int(c) * 10000 / 2 ** 32)) for c in cum]
    lines = [
        '/*',
        " * GENERATED by scripts/fe16_hit_table.py from Three Houses' hit roll (the program's 0x5bb8a0): the true hit, in basis points,",
        ' * for each displayed hit 0-100, counted over every state of the battle\'s random number generator. Do not edit by hand.',
        ' */',
        'export const FE16_TRUE_HIT: readonly number[] = ' + str(table),
        '',
    ]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
