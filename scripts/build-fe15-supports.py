"""
Echoes: Shadows of Valentia's support points, from the game's tuning values (params.bin at the root of its romfs): writes
src/data/fe15/fe15Supports.ts. Each value is a label pointing at [name, type ('I' int, 'F' float, 'S' a sub-table), value, step,
min, max]; the support ones:

  加算支援値出撃時       points for being deployed in the same battle
  加算支援値戦闘距離１-４ points for fighting with the partner 1-4 tiles away
  加算支援値杖使用時     points for using a staff on the partner
  マップ内支援値アップ上限 the most a pair earns in one battle

    python scripts/build-fe15-supports.py
"""
import json
import os
import struct

from fe15_bin import load

OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'fe15', 'fe15Supports.ts')


def params():
    b = load('params.bin.lz')
    out = {}
    for o, name in b.labels:
        kind, value = b.u32(o + 4), struct.unpack_from('<i', b.d, 0x20 + o + 8)[0]
        if kind == ord('I'):
            out[name] = value
    return out


def main():
    p = params()
    data = {
        'deployed': p['加算支援値出撃時'],
        'distance': [p[f'加算支援値戦闘距離{n}'] for n in '１２３４'],
        'staff': p['加算支援値杖使用時'],
        'perBattle': p['マップ内支援値アップ上限'],
    }
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/*\n * GENERATED by scripts/build-fe15-supports.py from Echoes\' tuning values (params.bin). Do not edit by hand.\n */\n\n'
                '/** Support points a pair earns in battle: for being deployed together, by how far apart they fight (1-4 tiles), for a staff '
                'used on the partner, and the most in one battle. */\n'
                f'export const FE15_SUPPORT_POINTS = {json.dumps(data)} as const\n')
    print(data)


if __name__ == '__main__':
    main()
