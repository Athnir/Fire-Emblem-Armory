"""
Echoes: Shadows of Valentia's supports: the points a pair earns, from the game's tuning values (params.bin at the root of its romfs),
and how far a partner's bonus reaches, from the program (code.bin): writes src/data/fe15/fe15Supports.ts. Each tuning value is a label
pointing at [name, type ('I' int, 'F' float, 'S' a sub-table), value, step, min, max]; the support ones:

  加算支援値出撃時       points for being deployed in the same battle
  加算支援値戦闘距離１-４ points for fighting with the partner 1-4 tiles away
  加算支援値杖使用時     points for using a staff on the partner
  マップ内支援値アップ上限 the most a pair earns in one battle

What a support gives in battle (0x3111b0, run for each side of the battle calculation 0x2ee950, so for the forecast and the fight, the
attacker and the defender): every unit on a tile 1 to 3 steps (|dx| + |dy|) from the tile the unit fights from (the scan over x and y
±3 at 0x3111f0-0x31128c, kept where 1 <= the distance <= 3 at 0x3112f8-0x311300), other than the unit itself and in its own army (the
army byte of each unit's +0xcc, compared at 0x311338: foes' pairs too), adds its row of the unit's support table (Reliance.bin's
支援効果, found by 0x1f78f4) at the pair's current rank (0x1f8820's +0x18, 0 with no record; the row entry + 4 + 4 × rank, 0x311370):
hit, crit, avoid and crit avoid, each row already the whole bonus at its rank, so ranks don't stack. Every partner in reach is added,
with no cap (0x311434-0x31147c, reached both from a slot of the four kept for the forecast's portraits, 0x311424, and with no slot
left, 0x311430); the forecast shows the four that give the most.

    python scripts/build-fe15-supports.py
"""
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fe15_bin import load  # noqa: E402
from fe15_code import dis, u32  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'fe15', 'fe15Supports.ts')
# The instructions the reading above relies on, so a different dump fails here rather than giving wrong words.
CODE = {
    0x3111F0: 0xE2430003,  # sub r0, r3, #3: the scan starts 3 columns left
    0x311220: 0xE2411003,  # sub r1, r1, #3: and 3 rows up
    0x311254: 0xE2811003,  # add r1, r1, #3: to 3 columns right
    0x31128C: 0xE2811003,  # add r1, r1, #3: and 3 rows down
    0x3112F8: 0xE2400001,  # sub r0, r0, #1: the distance less 1 ...
    0x3112FC: 0xE3500003,  # cmp r0, #3: ... below 3 (unsigned): 1 to 3 steps
    0x311300: 0x2A00005E,  # bhs: a tile outside that is skipped
    0x311338: 0xE1530001,  # cmp r3, r1: the two units' armies
    0x311368: 0x15D01018,  # ldrbne r1, [r0, #0x18]: the pair's rank, 0 with no record
    0x311370: 0xE080E101,  # add lr, r0, r1, lsl #2: the row at that rank alone
    0x311424: 0xEA000002,  # b: a partner given a forecast slot is still added
    0x31142C: 0xE3560004,  # cmp r6, #4: the forecast's slots, kept for the partners that give the most
    0x311430: 0xBAFFFFDA,  # blt: and so is one with no slot left
}


def params():
    b = load('params.bin.lz')
    out = {}
    for o, name in b.labels:
        kind, value = b.u32(o + 4), struct.unpack_from('<i', b.d, 0x20 + o + 8)[0]
        if kind == ord('I'):
            out[name] = value
    return out


def compared(addr):
    """The immediate a 'cmp rX, #n' at addr compares with."""
    (_, m, o), = dis(addr, 1)
    assert m == 'cmp' and '#' in o, (hex(addr), m, o)
    return int(o.split('#')[1], 0)


def main():
    for addr, word in CODE.items():
        assert u32(addr) == word, f'{addr:#x}: {u32(addr):#010x}'
    p = params()
    data = {
        'deployed': p['加算支援値出撃時'],
        'distance': [p[f'加算支援値戦闘距離{n}'] for n in '１２３４'],
        'staff': p['加算支援値杖使用時'],
        'perBattle': p['マップ内支援値アップ上限'],
        'reach': compared(0x3112FC),     # the farthest a partner counts: the distance less 1 is below it
        'forecast': compared(0x31142C),  # the slots the forecast's portraits come from
    }
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/*\n * GENERATED by scripts/build-fe15-supports.py from Echoes\' tuning values (params.bin) and its program (code.bin). Do not '
                'edit by hand.\n */\n\n'
                '/** Support points a pair earns in battle: for being deployed together, by how far apart they fight (1-4 tiles), for a staff '
                'used on the partner, and the most in one battle. `reach`: the farthest a partner in the same army gives its bonus, in steps '
                "from the tile the unit fights from (0x3111b0); `forecast`: how many partners the forecast shows (every one in reach "
                'counts). */\n'
                f'export const FE15_SUPPORT_POINTS = {json.dumps(data)} as const\n')
    print(data)


if __name__ == '__main__':
    main()
