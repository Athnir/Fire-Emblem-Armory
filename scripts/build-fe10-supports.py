"""
Radiant Dawn's support bonuses and support points, from the game's own tables in FE10Data.cms:
- `DivineData`: the affinities, as Path of Radiance's (9 rows of 12 bytes: a name pointer, then Atk, Def, Hit, Avoid, Crit and
  Crit avoid, stored doubled, and 2 bytes of padding). The program reads it through 0x8010b250.
- `RelianceParam`: the points each support level needs in total, what each action is worth for a middling pair, and how much
  more or less the five kinds of pair get.

The battle code (main.dol 0x800282a0 -> 0x8002fab0 -> 0x8002fc64) takes the one partner a unit has (0x8012e3a4: a single
field holds it), within 3 tiles and in the same army, adds both rows x the pair's level and halves the total once, a half
rounded up (0x80119760: (doubled sum + 1) >> 1).

    python scripts/build-fe10-supports.py   ->  src/data/supports/fe10Supports.ts
"""
import importlib.util
import json
import os
import struct

from fe10_files import GameData, read_text

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'data', 'supports', 'fe10Supports.ts')
_spec = importlib.util.spec_from_file_location('sup9', os.path.join(HERE, 'build-fe9-supports.py'))
sup9 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(sup9)
# What each action is worth, by its byte in RelianceParam (bytes 5 and 10 aren't shown: what reads them wasn't found).
ACTIONS = [(9, 'Shove or Smite the other unit'), (6, 'Start a turn next to the other unit'),
           (8, 'Use a staff or Sacrifice on the other unit'), (7, 'Start a turn carrying the other unit'),
           (4, 'Both start the chapter on the map (once per chapter)')]


def main():
    g = GameData()
    text = read_text()
    tables = sup9.named_tables(g.d)
    o = tables['DivineData']
    rows = []
    for i in range(struct.unpack_from('>I', g.d, o)[0]):
        r = o + 4 + 12 * i
        name = g.string(struct.unpack_from('>I', g.d, r)[0])
        atk, df, hit, avo, crit, dodge = g.d[r + 4:r + 10]
        if name == 'none':
            continue
        assert crit == dodge == 0, name  # no affinity gives Crit or Crit avoid
        rows.append({'name': text[sup9.LABELS[name]], 'atk': atk / 2, 'def': df / 2, 'hit': hit / 2, 'avoid': avo / 2})
    assert len(rows) == 8
    p = g.d[tables['RelianceParam']:tables['RelianceParam'] + 16]
    totals = list(p[0:3])
    offsets = [b - 256 if b > 127 else b for b in p[11:16]]
    lines = [
        "import type { Affinity } from './fe9Supports'",
        '',
        '/*',
        " * GENERATED by scripts/build-fe10-supports.py from Radiant Dawn's own tables (FE10Data.cms's DivineData and",
        ' * RelianceParam). Do not edit by hand.',
        ' */',
        'export const FE10_AFFINITIES: Affinity[] = [',
        *[f"  {{ name: {json.dumps(r['name'])}, atk: {r['atk']:g}, def: {r['def']:g}, hit: {r['hit']:g}, avoid: {r['avoid']:g} }},"
          for r in rows],
        ']',
        '',
        '/** A pair\'s bonus at a support level (C = 1, B = 2, A = 3): both affinities added, times the level, a half rounded up. */',
        'export function fe10SupportBonus(a: Affinity, b: Affinity, level: number) {',
        "  const total = (k: 'atk' | 'def' | 'hit' | 'avoid') => Math.floor((a[k] + b[k]) * level + 0.5)",
        '  return { atk: total(\'atk\'), def: total(\'def\'), hit: total(\'hit\'), avoid: total(\'avoid\') }',
        '}',
        '',
        '/**',
        f" * Support points, from RelianceParam (bytes {' '.join(f'{b:02x}' for b in p)}): the points each level needs in total",
        ' * (bytes 0-2), what each action is worth for a middling pair (bytes 4-9), and how much more or less the five kinds of',
        ' * pair get (bytes 11-15). Which kind a pair is depends on the two characters.',
        ' */',
        f"export const FE10_SUPPORT_TOTALS = [{', '.join(map(str, totals))}] as const",
        f"export const FE10_PAIR_OFFSETS = [{', '.join(map(str, offsets))}] as const",
        'export const FE10_SUPPORT_ACTIONS: { action: string; points: number }[] = [',
        *[f'  {{ action: {json.dumps(label)}, points: {p[i]} }},' for i, label in ACTIONS],
        ']',
        '',
    ]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
