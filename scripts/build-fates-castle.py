"""
Builds src/data/weapons/fatesCastle.ts: what My Castle's ally gifts and Lottery need besides the item table (whose gift pools,
gates and lottery ranks build-fates-items.py writes into gameItems.ts).

- Each story chapter's progress number (its chapter record's signed byte +0x12, GameData.bin). The game keeps the highest one
  of any story chapter cleared (code at 0x1b7300 only raises it, and only for records whose byte +9 is 0), and an ally's gift
  can be an item whose gate is at or below it (filter 0x4319f0). The numbers are the same on every route; checked here.
- The chapter that must be completed before each Lottery level opens (castle_building.bin's KID_クジ引き屋_1..3 records,
  read as build-fates-shops.py reads the shops').
- Which building levels can give each lottery rank: the rank weights are in the game's code (0x4dc040), not in a file. Levels
  1, 2, 3 weigh ranks 1-5 as 60/30/10/0/0, 35/40/20/5/0 and 0/35/40/20/5; a rank is drawable where its weight isn't 0.

Needs the dumped game files in data-raw/fates/romfs/ (git-ignored). Run:
    python scripts/build-fates-castle.py
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fates_lz import decompress  # noqa: E402
from fates_maps import RAW, ROOT  # noqa: E402

OUT = os.path.join(ROOT, 'src', 'data', 'weapons', 'fatesCastle.ts')
B = 0x20
CHAPTER_RECORD = 28
ROUTES = {'A': 'Birthright', 'B': 'Conquest', 'C': 'Revelation'}
# From the game's code (0x4dc040): each Lottery level's weight for ranks 1 to 5.
RANK_WEIGHTS = {1: [60, 30, 10, 0, 0], 2: [35, 40, 20, 5, 0], 3: [0, 35, 40, 20, 5]}


def strings(d):
    def s(ptr):
        o = B + ptr
        if not 0 < ptr < len(d) - B:
            return None
        try:
            t = d[o:d.index(b'\0', o)].decode('shift_jis')
        except (ValueError, UnicodeDecodeError):
            return None
        return t if t and t.isprintable() else None
    return s


def progress():
    """{chapter number: progress} for the story chapters, the same on every route."""
    d = decompress(open(os.path.join(RAW, 'GameData.bin.lz'), 'rb').read())
    s = strings(d)
    by_route = {route: {} for route in ROUTES.values()}
    for o in range(B, len(d) - CHAPTER_RECORD, 4):
        m = re.fullmatch(r'CID_([ABC])(\d{3})', s(struct.unpack_from('<I', d, o)[0]) or '')
        if not m:
            continue
        r = d[o:o + CHAPTER_RECORD]
        n = int(m.group(2))
        value = r[0x12] - 256 if r[0x12] > 127 else r[0x12]
        assert r[9] == 0, f'{m.group(0)} would not raise the progress number'
        # The shared chapters (Prologue to 6) are the cartridge's A-numbered files on every route.
        routes = ROUTES.values() if m.group(1) == 'A' and n <= 6 else [ROUTES[m.group(1)]]
        for route in routes:
            by_route[route].setdefault(n, value)
    out = {}
    for route, chapters in by_route.items():
        for n, v in chapters.items():
            assert out.setdefault(n, v) == v, f'chapter {n} differs on {route}'
    assert sorted(out) == list(range(len(out))), 'a story chapter is missing'
    return [out[n] for n in sorted(out)]


def lottery_chapters():
    d = decompress(open(os.path.join(RAW, 'castle', 'castle_building.bin.lz'), 'rb').read())
    s = strings(d)
    levels = {}
    for o in range(B, B + struct.unpack_from('<I', d, 4)[0], 4):
        m = re.fullmatch(r'KID_クジ引き屋_([123])', s(struct.unpack_from('<I', d, o)[0]) or '')
        if not m:
            continue
        chapters = {int(c[1:]) for c in (s(struct.unpack_from('<I', d, o + off)[0]) for off in (0x34, 0x38, 0x3C)) if c}
        assert len(chapters) == 1, (m.group(0), chapters)
        levels[int(m.group(1))] = chapters.pop()
    assert sorted(levels) == [1, 2, 3], levels
    return [levels[i] for i in (1, 2, 3)]


def main():
    prog = progress()
    lottery = lottery_chapters()
    rank_levels = {rank: [lv for lv in (1, 2, 3) if RANK_WEIGHTS[lv][rank - 1]] for rank in range(1, 6)}
    lines = [
        '/*',
        " * GENERATED by scripts/build-fates-castle.py from the game's chapter table, castle_building.bin and the lottery's",
        " * rank weights in the game's code. Do not edit by hand.",
        ' */',
        '',
        "/** Each story chapter's progress number (index 0 is the Prologue): the highest one cleared decides which ally gifts can come up. */",
        f'export const FATES_PROGRESS: number[] = {prog}',
        '',
        '/** The chapter that must be completed before each level of the Lottery opens (levels 1 to 3). */',
        f'export const LOTTERY_CHAPTERS: number[] = {lottery}',
        '',
        '/** The Lottery levels whose draws can give an item of each rank (1 to 5). */',
        'export const LOTTERY_RANK_LEVELS: Record<number, number[]> = {'
        + ', '.join(f'{rank}: {levels}' for rank, levels in rank_levels.items()) + '}',
    ]
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('wrote', OUT, 'progress', prog, 'lottery', lottery, 'ranks', rank_levels)


if __name__ == '__main__':
    main()
