"""
Builds src/data/fe3/fe3Supports.ts: what Mystery of the Emblem's supports give, read from the user's clean ROM (scripts/fe3_rom.py).
Run:
    python scripts/build-fe3-supports.py

The game has no support levels or conversations. $83:B9E1 marks every tile within 3 steps of the unit ($80:B10B with a pseudo-class,
0x2E, that pays 1 on every terrain: $88:CC8F), then for each unit of the same side standing on one adds:
  - 10 if it carries the Geosphere (item 0x3C, or 0x6B, the item form) in its item slots ($83:BA64);
  - the bonus of every entry of the table at $88:CD31 (3 bytes: the giver's name id, the receiver's, the bonus; ended by FF) whose
    giver is that unit and receiver the one being helped ($83:BA85).
The total goes to the unit's hit, avoid, crit and crit avoid ($83:B445, $83:B47D, $83:B57C, $83:B5B5). Who supports whom is unit data
(the Unit Planner's), so only the amounts are written.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fe3_rom as r  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fe3', 'fe3Supports.ts')


def main():
    assert r.R[r.lo(0x83BA08):r.lo(0x83BA08) + 2] == bytes([0xA9, 0x03]), 'the support reach (3 steps)'
    assert r.R[r.lo(0x83BA6E):r.lo(0x83BA6E) + 4] == bytes([0xC9, 0x6B, 0xF0, 0x04]), 'the Geosphere check'
    assert set(r.move_costs(0x2E)) == {1}, 'the reach counts every tile as 1'
    entries = r.supports()
    pairs = {(g, v) for g, v, _ in entries}
    data = {'reach': 3, 'bonuses': sorted({b for _, _, b in entries}), 'entries': len(entries),
            'oneWay': sum(1 for g, v, _ in entries if (v, g) not in pairs), 'geosphere': r.u8(0x83BA77)}
    lines = [
        '/*',
        " * GENERATED by scripts/build-fe3-supports.py from Mystery of the Emblem's supports table ($88:CD31) and support code.",
        ' * Do not edit by hand.',
        ' */',
        '',
        '/** What a support gives: the bonus amounts the table uses, how close the partner must be, how many entries the table has and',
        " * how many of them go one way only, and what carrying the Geosphere gives every ally in reach. */",
        f'export const FE3_SUPPORTS = {json.dumps(data, indent=2)} as const',
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(data)


if __name__ == '__main__':
    main()
