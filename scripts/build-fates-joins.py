"""
Builds src/data/maps/fatesJoins.ts from Serenes Forest's recruitment pages: the chapter each character joins your army for
good, on each route (a temporary guest who leaves, like Ryoma in Chapter 6, doesn't count; the row marked "(perm.)" does).

The cartridge dump holds the chapter scripts but not a table of who joins when, so this is the Serenes Forest source. The
children's paralogues open the chapter after their fixed parent joins, which needs these. Needs a network connection. Run:
    python scripts/build-fates-joins.py
"""
import json
import os
import re
import urllib.request
from html.parser import HTMLParser

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'src', 'data', 'maps', 'fatesJoins.ts')
BASE = 'https://serenesforest.net/fire-emblem-fates/'
# Birthright's characters are the Hoshidan page, Conquest's the Nohrian one.
PAGES = {'Birthright': 'hoshidan-characters/recruitment/', 'Conquest': 'nohrian-characters/recruitment/', 'Revelation': 'revelation/character-recruitment/'}


class Tables(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tables, self.row, self.cell = [], None, None

    def handle_starttag(self, tag, attrs):
        if tag == 'table':
            self.tables.append([])
        elif tag == 'tr' and self.tables:
            self.row = []
        elif tag in ('td', 'th') and self.row is not None:
            self.cell = ''

    def handle_endtag(self, tag):
        if tag in ('td', 'th') and self.row is not None and self.cell is not None:
            self.row.append(' '.join(self.cell.split()))
            self.cell = None
        elif tag == 'tr' and self.row is not None:
            if self.row:
                self.tables[-1].append(self.row)
            self.row = None

    def handle_data(self, data):
        if self.cell is not None:
            self.cell += data


def joins(page):
    req = urllib.request.Request(BASE + page, headers={'User-Agent': 'Mozilla/5.0'})
    parser = Tables()
    parser.feed(urllib.request.urlopen(req, timeout=60).read().decode('utf-8', 'replace'))
    out = {}
    for table in parser.tables:
        for r in table:
            # Name, Class, Ch., Recruit/Note, Exclusive: the chapter is a plain number (children's are '2x', Izana's '19~').
            if len(r) >= 4 and re.fullmatch(r'\d+', r[2]):
                name = re.sub(r'\s*\((perm|temp)\.\)', '', r[0])
                if '(temp.)' in r[0]:
                    continue
                out.setdefault(name, int(r[2]))
    return out


def main():
    data = {route: joins(page) for route, page in PAGES.items()}
    lines = [
        '/*',
        " * GENERATED by scripts/build-fates-joins.py from Serenes Forest's recruitment pages. Do not edit by hand.",
        ' */',
        '',
        '/** The chapter each character joins your army for good, by route (a temporary guest who leaves doesn\'t count). */',
        'export const FATES_JOINS: Record<string, Record<string, number>> = ' + json.dumps(data, ensure_ascii=False),
    ]
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('wrote', OUT, {r: len(v) for r, v in data.items()})


if __name__ == '__main__':
    main()
