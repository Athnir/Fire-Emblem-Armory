"""
New Mystery of the Emblem's supports, read in the battle code (overlay 00, the support routine at 0x21f2e0c, which sets up each side of a
battle): writes src/data/fe12/fe12Supports.ts.

For each side, every unit of its own army within 3 tiles (counted in steps, 0x21f2e9c-0x21f2ef8 and 0x21f2f8c) of where it fights that
is one of the side's five partners (Person +0x30, 8 bytes each: one way, the side's own list) adds by the support level its points
reach (+5 C, +6 B, +7 A of the slot): the hit, avoid, crit and crit avoid below (0x21f3380-0x21f341c). Then every unit of that army in
the same reach holding an item whose +0x28 has 0x400 (the Geosphere) adds crit (0x21f3430-0x21f344c). Several add up. None of it
applies in the arena (the battle's +0x3c, 0x21f2e58), nor to the foe's army in the story (only the wireless modes set the global flag
0x20 that lets it, 0x21f2e14-0x21f2e50).

    python scripts/build-fe12-supports.py
"""
import json
import os
import struct

import capstone

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OVERLAY = os.path.join(ROOT, 'data-raw', 'fe12', 'rom', 'overlay', '00_021cbac0.bin')
BASE = 0x021cbac0
OUT = os.path.join(ROOT, 'src', 'data', 'fe12', 'fe12Supports.ts')

CODE = open(OVERLAY, 'rb').read()
MD = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_ARM)


def ins(addr):
    i = next(MD.disasm(CODE[addr - BASE:addr - BASE + 4], addr))
    return i.mnemonic, i.op_str


def imm(addr, mnemonic):
    """The immediate of the instruction at addr, checking it's the one expected."""
    m, ops = ins(addr)
    assert m == mnemonic and '#' in ops, (hex(addr), m, ops)
    return int(ops.split('#')[-1], 0)


def main():
    # The reach: the box (x - 3 .. x + 3, y - 3 .. y + 3), then the steps (dx + dy) held at 3.
    reach = imm(0x21f2e9c, 'sub')
    assert imm(0x21f2ed8, 'add') == reach and imm(0x21f2f8c, 'cmp') == reach
    slots = imm(0x21f3424, 'cmp')
    # Each stat: A (level 3), B (2), C (1); the routine stores hit at +0x1c, avoid +0x24, crit +0x20, crit avoid +0x28.
    hit = {'A': imm(0x21f3384, 'moveq'), 'B': imm(0x21f3390, 'moveq'), 'C': imm(0x21f3398, 'mov')}
    avoid = {'A': imm(0x21f33b8, 'moveq'), 'B': imm(0x21f33c4, 'moveq'), 'C': imm(0x21f33cc, 'mov')}
    crit = {'A': imm(0x21f33ec, 'moveq'), 'B': 0, 'C': 0}
    crit_avoid = {'A': imm(0x21f3408, 'moveq'), 'B': 0, 'C': 0}
    assert ins(0x21f33f0) == ('movne', 'r1, #0') and ins(0x21f340c) == ('movne', 'r0, #0'), 'only A gives crit and crit avoid'
    for addr, field in ((0x21f33b4, '0x1c'), (0x21f33e8, '0x24'), (0x21f3404, '0x20'), (0x21f341c, '0x28')):
        m, ops = ins(addr)
        assert m == 'strh' and ops.endswith(f'#{field}]'), (hex(addr), m, ops)
    # The Geosphere: an item with +0x28 0x400 held (0x204fcd8) adds crit.
    assert imm(0x21f3434, 'mov') == 0x400
    geosphere = imm(0x21f3448, 'addne')
    levels = {lv: {'hit': hit[lv], 'avoid': avoid[lv], 'crit': crit[lv], 'critAvoid': crit_avoid[lv]} for lv in ('C', 'B', 'A')}
    data = {'reach': reach, 'slots': slots, 'levels': levels, 'geosphere': geosphere}
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/*\n * GENERATED by scripts/build-fe12-supports.py from New Mystery of the Emblem\'s support code (overlay 00, 0x21f2e0c).\n'
                ' * Do not edit by hand.\n */\n\n'
                '/** What a support gives: how close a partner must be, how many partners a unit has, the hit, avoid, crit and crit avoid each\n'
                ' * level adds, and the crit the Geosphere adds. */\n'
                f'export const FE12_SUPPORTS = {json.dumps(data, indent=2)} as const\n')
    print(data)


if __name__ == '__main__':
    main()
