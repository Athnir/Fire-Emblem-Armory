"""
Builds src/data/fe16/fe16Supports.ts: what a support gives in Three Houses, per level, read from the game's own tables and program
(scripts/fe16_data.py; data-raw/fe16/README.md). Run:
    python scripts/build-fe16-supports.py

A battle unit's support bonuses are added at `0xd9330` (called for each of the up to three allies in a Linked Attack and the
attacker's adjutant, `0xd91a0`): a pair the support table holds (fixed_persondata.bin section 9: 23 pairs, u16 + u16 persons, then
five stats by five levels) adds its own record's values, any other pair the partner's own record (section 8: one per playable
character); the level is the pair's support rank through `0xcea420` (C and C+ level 1, B and B+ 2, A and A+ 3, S 4; a pair with
supports but none unlocked 0), and a pair that can't support adds nothing (`0x41c040`). The five stats go to the battle unit's +0xcc,
+0xb8, +0xbc, +0xb4 and +0xb0: the hit routine (`0xd9560`) adds +0xb4 (hit), the attack sum (`0xd9140`) +0xb0 (attack), and +0xbc is
avoid; +0xb8 (crit) and +0xcc are 0 in every record. When the attack is a gambit, the ally adds instead the program's own Gambit
Boost (attack and hit by level, `0x1aa83f8`-`0x1aa8440`).
"""
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fe16_data as D  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fe16', 'fe16Supports.ts')
LEVELS = ['None', 'C', 'B', 'A', 'S']
RANKS = ['C', 'C+', 'B', 'B+', 'A', 'A+', 'S']
RANK_LEVELS = 0xcea420      # support rank 1-7 -> bonus level (u32 each)
GAMBIT_HIT = (0x3f8, 0x400, 0x408, 0x410, 0x418)       # GOT entries (from 0x1aa8000) of the gambit boost's hit by level
GAMBIT_ATTACK = (0x420, 0x430, 0x438, 0x428, 0x440)    # and its attack, in the order the routine stores them


def stats(r, base):
    """A record's five stats by five levels from `base`: (attack, avoid, hit), each by level; crit and +0xcc must be 0."""
    rows = [list(r[base + 5 * k:base + 5 * k + 5]) for k in range(5)]
    cc, crit, avoid, hit, attack = rows
    assert not any(cc) and not any(crit), rows
    return attack, avoid, hit


def main():
    main_bin = open(os.path.join(D.ROMFS, 'main.bin'), 'rb').read()
    rank_levels = list(struct.unpack_from('<7i', main_bin, RANK_LEVELS))
    got = lambda o: struct.unpack_from('<i', main_bin, struct.unpack_from('<Q', main_bin, 0x1aa8000 + o)[0])[0]  # noqa: E731
    gambit = {'attack': [got(o) for o in GAMBIT_ATTACK], 'hit': [got(o) for o in GAMBIT_HIT]}
    # Every playable character's own record (section 8; Sothis's is empty) is the same: hit and avoid by level, no attack.
    own = {json.dumps(stats(r, 0)) for p, r in enumerate(D.table(D.PERSONDATA, 8)) if any(r) and p < 37}
    assert len(own) == 1, own
    attack, avoid, hit = json.loads(own.pop())
    pairs = D.table(D.PERSONDATA, 9)
    special = {json.dumps(stats(r, 4)) for r in pairs}
    assert len(special) == 1, special
    p_attack, p_avoid, p_hit = json.loads(special.pop())
    assert (p_avoid, p_hit) == (avoid, hit) and not any(attack), (p_avoid, p_hit, attack)
    data = {
        'levels': LEVELS,
        'rankLevels': {rank: LEVELS[lv] for rank, lv in zip(RANKS, rank_levels)},
        'linked': {'hit': hit, 'avoid': avoid, 'pairAttack': p_attack, 'pairs': len(pairs)},
        'gambit': gambit,
    }
    lines = [
        '/*',
        " * GENERATED by scripts/build-fe16-supports.py from Three Houses' support tables (fixed_persondata.bin sections 8 and 9) and",
        ' * its program. Do not edit by hand.',
        ' */',
        '',
        '/** What one ally gives by its support level with the attacker: in a Linked Attack, hit and avoid (attack too for the pairs the',
        " * game's support table holds); in a Gambit Boost, attack and hit. */",
        'export const FE16_SUPPORTS = ' + json.dumps(data, indent=2) + ' as const',
    ]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', OUT, data)


if __name__ == '__main__':
    main()
