"""
Builds src/data/fe17/fe17Supports.ts: what a support gives in Fire Emblem Engage, per support type and level, read from the game's own
support table (reliance.xml, sheet 支援効果) and checked in its program (scripts/fe17_data.py; data-raw/fe17/README.md). Run:
    python scripts/build-fe17-supports.py

`App.SupportCalculator` (Range 1) looks at the four tiles beside a unit: each ally of its army standing there that has a support
with it adds the row of the ally's own support type (its person's SupportCategory) at the pair's level (`App.UnitReliance.
TryGetSupportData`: none, no bonus; C, B, A and the ring the four rows), each of Hit, Crit, Avoid and Dodge summed over them
(`RangeFunction`).
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fe17_data as D  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fe17', 'fe17Supports.ts')
# The types by their table names; the game shows none of them, so each goes by what it raises most.
TYPES = {'デフォルト': 'Default', 'バランス': 'Balanced', '命中': 'Hit', '必殺': 'Crit', '回避': 'Avoid', '必殺回避': 'Dodge'}
LEVELS = ['C', 'B', 'A', 'Ring']


def main():
    types, current = [], None
    for r in D.rows('reliance', '支援効果'):
        if r['Name']:
            current = {'type': TYPES[r['Name']], 'levels': []}
            types.append(current)
            continue
        current['levels'].append({'level': LEVELS[int(r['Level']) - 1], 'hit': int(r['Hit']), 'crit': int(r['Critical']),
                                  'avoid': int(r['Avoid']), 'dodge': int(r['Secure'])})
    assert all(len(t['levels']) == 4 for t in types), types
    lines = [
        '/*',
        " * GENERATED by scripts/build-fe17-supports.py from Fire Emblem Engage's support table (reliance.xml). Do not edit by hand.",
        ' */', '',
        "/** Each support type's bonus by level: what an adjacent supporter of that type gives. */",
        'export const FE17_SUPPORTS = ' + json.dumps(types, indent=2, ensure_ascii=False) + ' as const',
    ]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', OUT, [t['type'] for t in types])


if __name__ == '__main__':
    main()
