"""
Builds src/data/fe7/fe7Supports.ts and src/data/fe8/fe8Supports.ts: the support bonuses of The Blazing Blade and The Sacred Stones,
read from each game's battle code (scripts/gba_rom.py). Run:
    python scripts/build-gba-supports.py

Both games use The Binding Blade's routine (scripts/build-fe6-supports.py) with new addresses:
  - The partner walk (FE7 0x08026A18, FE8 0x080285B0): a partner counts when it's on the map within 3 tiles (|dx| + |dy| <= 3) with a
    support level above 0; for each, the partner's affinity row and the unit's own, each times the level (FE7 0x080269B0, FE8
    0x08028550), summed, then each total halved once, rounding down (the six `lsrs #1` at FE7 0x08026AE6, FE8 0x0802867E).
  - The rows are 8-byte records (affinity id, Atk, Def, Hit, Avoid, Crit, Dodge, 0) up to a 0 id, loaded from the literal pool
    (FE7 0x08026998, FE8 0x08028534).
  - Support levels from support points (FE7 0x08026690, FE8 0x0802823C): over 240 = A, over 160 = B, over 80 = C.
  - A support can only grow while both units hold 4 levels or fewer in total (FE7 0x0802696C, FE8 0x08028508): 5 at most.
Affinity ids 1-7 are named by the games' support screens' order (Fire, Thunder, Wind, Ice, Dark, Light, Anima).
"""
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gba_rom import rom  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data')
NAMES = {1: 'Fire', 2: 'Thunder', 3: 'Wind', 4: 'Ice', 5: 'Dark', 6: 'Light', 7: 'Anima'}
LITERAL = {'fe7': 0x26998, 'fe8': 0x28534}
LEVELS = {'fe7': 0x26690, 'fe8': 0x2823C}
GAME_NAME = {'fe7': 'The Blazing Blade', 'fe8': 'The Sacred Stones'}


def thresholds(r, start):
    """The three `cmp r0, #n` of the level routine (A, B, C, in that order): a level needs more than n points."""
    out = []
    for o in range(start, start + 0x30, 2):
        ins = struct.unpack_from('<H', r.R, o)[0]
        if ins >> 8 == 0x28 and ins & 0xFF > 1:
            out.append((ins & 0xFF) + 1)
    a, b, c = out
    return {'C': c, 'B': b, 'A': a}


def main():
    for g in ('fe7', 'fe8'):
        r = rom(g)
        table = r.cfg['affinities']
        assert r.u32(LITERAL[g]) == 0x08000000 + table, 'the affinity lookup loads its table from the literal pool'
        rows, o = [], table
        while r.R[o]:
            aff, atk, df, hit, avo, crit, dodge = struct.unpack_from('<7B', r.R, o)
            rows.append({'name': NAMES[aff], 'atk': atk, 'def': df, 'hit': hit, 'avoid': avo, 'crit': crit, 'dodge': dodge})
            o += 8
        data = {'affinities': rows, 'levels': thresholds(r, LEVELS[g]), 'reach': 3, 'maxLevels': 5}
        const = g.upper() + '_SUPPORTS'
        lines = [
            '/*',
            f" * GENERATED by scripts/build-gba-supports.py from {GAME_NAME[g]}'s battle code. Do not edit by hand.",
            ' */',
            '',
            "/** Each affinity's bonus per support level (summed over every partner in range, then halved and rounded down). */",
            f'export const {const} = {json.dumps(data, indent=2)} as const',
        ]
        out = os.path.join(ROOT, g, f'{g}Supports.ts')
        with open(out, 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(lines) + '\n')
        print(g, data['levels'])


if __name__ == '__main__':
    main()
