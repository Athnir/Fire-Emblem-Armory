"""
Path of Radiance's support bonuses, from the game's own affinity table: FE8Data.bin's `DivineData` (9 rows of 12 bytes: a
name pointer, then Atk, Def, Hit, Avoid, Crit and Crit avoid, stored doubled, and 2 bytes of padding). The program reads it
at main.dol 0x80019da8 and 0x800368c8; the battle code (0x801a8da4) adds (own row + partner's row) x level for every partner
within 3 tiles and halves the total once (0x8003b8d4).

    python scripts/build-fe9-supports.py   ->  src/data/supports/fe9Supports.ts
"""
import json
import os
import struct

from fe9_files import GameData, read_text

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'src', 'data', 'supports', 'fe9Supports.ts')
# The affinity's name in the table -> its label in the game's text (the status screen's names).
LABELS = {'fire': 'MDV_FI', 'thunder': 'MDV_TH', 'wind': 'MDV_WD', 'water': 'MDV_WAT', 'dark': 'MDV_D', 'light': 'MDV_LIT',
          'heaven': 'MDV_HV', 'telius': 'MDV_TELI'}


def named_tables(d):
    """FE8Data.bin's table directory: {name: file offset}. Header: size, data size, pointer count, name count; the data at
    0x20, then the pointer list, then (data offset, name offset) pairs, then the names."""
    _, dsize, nptr, nnames = struct.unpack_from('>4I', d, 0)
    pairs = 0x20 + dsize + 4 * nptr
    names = pairs + 8 * nnames
    out = {}
    for i in range(nnames):
        off, noff = struct.unpack_from('>2I', d, pairs + 8 * i)
        out[d[names + noff:d.index(b'\0', names + noff)].decode()] = 0x20 + off
    return out


def main():
    g = GameData()
    text = read_text()
    o = named_tables(g.d)['DivineData']
    rows = []
    for i in range(struct.unpack_from('>I', g.d, o)[0]):
        r = o + 4 + 12 * i
        name = g.string(struct.unpack_from('>I', g.d, r)[0])
        atk, df, hit, avo, crit, dodge = g.d[r + 4:r + 10]
        if name == 'none':
            continue
        assert crit == dodge == 0, name  # no affinity gives Crit or Crit avoid
        rows.append({'name': text[LABELS[name]], 'atk': atk / 2, 'def': df / 2, 'hit': hit / 2, 'avoid': avo / 2})
    assert len(rows) == 8
    lines = [
        '/*',
        " * GENERATED by scripts/build-fe9-supports.py from Path of Radiance's own affinity table (FE8Data.bin's DivineData).",
        ' * Do not edit by hand.',
        ' */',
        'export interface Affinity {',
        '  name: string',
        '  /** Per support level, for each unit of the pair. */',
        '  atk: number',
        '  def: number',
        '  hit: number',
        '  avoid: number',
        '}',
        '',
        'export const FE9_AFFINITIES: Affinity[] = [',
        *[f"  {{ name: {json.dumps(r['name'])}, atk: {r['atk']:g}, def: {r['def']:g}, hit: {r['hit']:g}, avoid: {r['avoid']:g} }},"
          for r in rows],
        ']',
        '',
        "export const FE9_LEVELS = ['C', 'B', 'A'] as const",
        '',
        "type Stat = 'atk' | 'def' | 'hit' | 'avoid'",
        "const STATS: Stat[] = ['atk', 'def', 'hit', 'avoid']",
        '',
        '/**',
        " * A unit's bonus from its partners in range: each partner adds (both affinities) x the pair's level (C = 1, B = 2, A = 3),",
        ' * and the sum is rounded down once (the game keeps the values doubled and halves the total).',
        ' */',
        'export function fe9SupportTotal(own: Affinity, partners: { affinity: Affinity; level: number }[]) {',
        '  const total = (k: Stat) => Math.floor(partners.reduce((sum, p) => sum + (own[k] + p.affinity[k]) * p.level, 0))',
        '  return Object.fromEntries(STATS.map((k) => [k, total(k)])) as Record<Stat, number>',
        '}',
        '',
        '/** A pair\'s bonus at a support level (1-3), for either unit, when no other partner is in range. */',
        'export function fe9SupportBonus(a: Affinity, b: Affinity, level: number) {',
        '  return fe9SupportTotal(a, [{ affinity: b, level }])',
        '}',
        '',
    ]
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print(OUT, len(rows), 'affinities')


if __name__ == '__main__':
    main()
