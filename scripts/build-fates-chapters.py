"""
Builds src/data/maps/gameChapters.ts from the game's text and terrain scripts: each chapter's title,
location and victory rule, its objective tiles (seize / defend / escape), what every chest and village
gives, and the in-game description of its Dragon Veins.

Needs the dumped game files in data-raw/fates/romfs/ (git-ignored). Run:
    python scripts/build-fates-chapters.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fates_cmb import Script  # noqa: E402
from fates_maps import MAPS, RAW, ROOT, terrain, terrain_script  # noqa: E402
from fates_terrain import read as read_terrain  # noqa: E402
from fates_text import read as read_text  # noqa: E402

OUT = os.path.join(ROOT, 'src', 'data', 'maps', 'gameChapters.ts')
VILLAGE, SEIZE, DEFEND, CHEST = 1, 3, 4, 10
ESCAPE = (5, 7, 8)


def clean(s):
    """Game text -> plain English: Corrin's name for $Nu, no layout codes or line breaks."""
    return ' '.join(s.replace('$Nu', 'Corrin').replace('$a', '').split())


def gains(s, h, item):
    """What a chest or village handler hands over: item names and gold, in script order."""
    ins = s.disasm(h)
    out = []
    for k, (_, n, a) in enumerate(ins):
        if n != 'call':
            continue
        if a.startswith('ev::ItemGain') and k and ins[k - 1][1] == 'str':
            out.append(item(ins[k - 1][2].strip("'")))
        elif a.startswith('ev::GoldGain') and k and ins[k - 1][1] == 'int':
            out.append(f'{ins[k - 1][2]:,} Gold')
    calls = {a.split('/')[0] for _, n, a in ins if n == 'call'}
    return list(dict.fromkeys(out)), calls


def main():
    text = read_text(os.path.join(RAW, 'm', '@E', 'GameData.bin.lz'))

    def item(iid):
        name = text.get('M' + iid, iid)
        # Gold-bag items ('5000G') read the way the rest of the app writes gold.
        return f'{int(name[:-1]):,} Gold' if name[:-1].isdigit() and name.endswith('G') else name

    result = {}
    for map_id, (code, route, chapter) in MAPS.items():
        t = read_terrain(terrain(code))
        H = t['h'] - 2
        objectives, objects = {}, []
        path = terrain_script(code)
        s = Script(path) if path else None
        for h in (s.handlers() if s else []):
            a = h['args']
            if len(a) < 5 or max(a[:4]) > 60:
                continue
            x, y, w, hh, kind = a[:5]
            tiles = [(x + i, H + 1 - (y + j)) for j in range(hh) for i in range(w)]
            if kind == SEIZE:
                objectives.setdefault('seize', []).extend(tiles)
            elif kind == DEFEND:
                objectives.setdefault('defend', []).extend(tiles)
            elif kind in ESCAPE:
                objectives.setdefault('escape', []).extend(tiles)
            elif kind in (CHEST, VILLAGE):
                got, calls = gains(s, h, item)
                if kind == CHEST:
                    objects.append({'type': 'chest', 'tile': tiles[0], 'contents': ' or '.join(got) or 'Nothing'})
                else:
                    extra = 'Visiting it brings enemy reinforcements.' if 'ev::Dispos' in calls else ''
                    objects.append({'type': 'village', 'tile': tiles[0], 'reward': ' or '.join(got), **({'note': extra} if extra else {})})
        title = text.get(f'MCID_{code}', code)
        rule = clean(text.get(f'MCID_RULE_{code}_TELOP') or text.get(f'MCID_RULE_{code}', ''))
        vein = text.get(f'MCID_DRAGONLINE_H_{code}')
        vein_normal = text.get(f'MCID_DRAGONLINE_H_{code}_NORMAL')
        result[map_id] = {
            'code': code, 'route': route, 'chapter': chapter, 'title': title, 'location': text.get(f'MCID_T_{code}', ''), 'rule': rule,
            'objectives': objectives, 'objects': objects,
            **({'veinEffect': clean(vein)} if vein else {}),
            **({'veinEffectNormal': clean(vein_normal)} if vein_normal else {}),
        }

    def tiles(ts):
        return '[' + ', '.join(f'[{x}, {y}]' for x, y in ts) + ']'

    lines = [
        "import type { ChapterMap, Tile } from './types'",
        '',
        '/*',
        " * GENERATED by scripts/build-fates-chapters.py from the game's text and terrain scripts.",
        ' * Do not edit by hand: fix the generator, or put notes on the map itself.',
        ' */',
        'export interface GameChapter {',
        '  code: string',
        "  route: ChapterMap['route']",
        '  /** 28 for the Endgame. */',
        '  chapter: number',
        '  title: string',
        '  location: string',
        "  /** The victory rule as the game words it (e.g. 'Defeat the boss'). */",
        '  rule: string',
        '  objectives: Partial<Record<"seize" | "defend" | "escape", Tile[]>>',
        '  objects: (',
        "    | { type: 'chest'; tile: Tile; contents: string }",
        "    | { type: 'village'; tile: Tile; reward: string; note?: string }",
        '  )[]',
        "  /** The game's own description of the chapter's Dragon Veins. */",
        '  veinEffect?: string',
        '  /** The same on Normal (Phoenix / Casual), where it differs. */',
        '  veinEffectNormal?: string',
        '}',
        '',
        'export const GAME_CHAPTERS: Record<string, GameChapter> = {',
    ]
    for map_id, c in result.items():
        lines.append(f"  '{map_id}': {{")
        lines.append(f"    code: '{c['code']}',")
        lines.append(f"    route: '{c['route']}',")
        lines.append(f"    chapter: {c['chapter']},")
        lines.append(f"    title: {json.dumps(c['title'])},")
        lines.append(f"    location: {json.dumps(c['location'])},")
        lines.append(f"    rule: {json.dumps(c['rule'])},")
        lines.append('    objectives: { ' + ', '.join(f'{k}: {tiles(v)}' for k, v in c['objectives'].items()) + ' },')
        lines.append('    objects: [')
        for o in c['objects']:
            tile = f"[{o['tile'][0]}, {o['tile'][1]}]"
            if o['type'] == 'chest':
                lines.append(f"      {{ type: 'chest', tile: {tile}, contents: {json.dumps(o['contents'])} }},")
            else:
                note = f", note: {json.dumps(o['note'])}" if 'note' in o else ''
                lines.append(f"      {{ type: 'village', tile: {tile}, reward: {json.dumps(o['reward'])}{note} }},")
        lines.append('    ],')
        for k in ('veinEffect', 'veinEffectNormal'):
            if k in c:
                lines.append(f'    {k}: {json.dumps(c[k])},')
        lines.append('  },')
    lines.append('}')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
