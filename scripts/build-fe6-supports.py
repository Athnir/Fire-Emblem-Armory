"""
Builds src/data/fe6/fe6Supports.ts: The Binding Blade's support bonuses, read from the battle code in the user's ROM
(scripts/fe6_rom.py). Run:
    python scripts/build-fe6-supports.py

The code (Thumb; disassemble with capstone):
  - 0x08022E3C walks a unit's support partners. A partner counts when it's on the map within 3 tiles (|dx| + |dy| <= 3, skipped by a
    flag in the chapter's state) and not dead or rescued (unit state 0x2C), with a support level above 0 (0x08022AF0: support
    points over 200 = A, over 120 = B, over 60 = C). For each such partner it adds the partner's affinity row and the unit's own
    affinity row, each times the level (0x08022DD4), then halves each total, rounding down (the six `lsrs #1` at 0x08022F08).
  - The rows are 8-byte records at 0x0866350C (affinity id, Atk, Def, Hit, Avoid, Crit, Dodge, 0), up to a 0 id.
  - 0x080247F0 adds the six totals to attack, defence, hit, avoid, crit and dodge.
  - A support can only grow while both units hold 4 levels or fewer in total (0x08022BC0, 0x08022BD0): 5 at most.
Affinity ids 1-7 are named by their order in the later GBA games and Serenes Forest (the game shows only icons).
"""
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fe6_rom import R, u32  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fe6', 'fe6Supports.ts')
NAMES = {1: 'Fire', 2: 'Thunder', 3: 'Wind', 4: 'Ice', 5: 'Dark', 6: 'Light', 7: 'Anima'}


def main():
    assert u32(0x22DBC) == 0x0866350C, 'the affinity lookup loads its table from the literal pool'
    rows, o = [], 0x66350C
    while R[o]:
        aff, atk, df, hit, avo, crit, dodge = struct.unpack_from('<7B', R, o)
        rows.append({'name': NAMES[aff], 'atk': atk, 'def': df, 'hit': hit, 'avoid': avo, 'crit': crit, 'dodge': dodge})
        o += 8
    # Support levels from support points (0x08022AF0): the cmp constants.
    thresholds = {'C': 61, 'B': 121, 'A': 201}
    data = {'affinities': rows, 'levels': thresholds, 'reach': 3, 'maxLevels': 5}
    lines = [
        '/*',
        " * GENERATED by scripts/build-fe6-supports.py from The Binding Blade's battle code. Do not edit by hand.",
        ' */',
        '',
        '/** Each affinity\'s bonus per support level (summed over every partner in range, then halved and rounded down). */',
        f'export const FE6_SUPPORTS = {json.dumps(data, indent=2)} as const',
    ]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(data)


if __name__ == '__main__':
    main()
