"""
Builds src/data/fe5/fe5Supports.ts: what Thracia 776's supports give, read from the user's clean ROM (scripts/fe5_rom.py). Run:
    python scripts/build-fe5-supports.py

The game has no support levels or conversations. $83:E5A5 walks the supports table at $88:80CD (5-byte entries: the character who
gets the bonus u16, the one who gives it u16, the bonus u8; ended by a 0 character) and, for every entry whose giver is alive, on
the map and within 3 tiles (counting steps: the CMP #$03 at $83:E613), adds the bonus to a running total. The total goes to the
unit's hit and avoid (with the triangle, leadership, Charm and terrain bonuses, $83:E2F3) and to its crit and crit avoid
($83:D3F8, $83:D41C). Who supports whom is unit data (the Unit Planner's), so only the amounts are written.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fe5_rom import R, lo, u8, u16  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fe5', 'fe5Supports.ts')
TABLE = 0x8880CD


def main():
    assert R[lo(0x83E613):lo(0x83E613) + 2] == bytes([0xC9, 0x03]), 'the support range check'
    entries, a = [], TABLE
    while u16(a):
        entries.append((u16(a), u16(a + 2), u8(a + 4)))
        a += 5
    data = {'reach': 3, 'bonuses': sorted({b for _, _, b in entries}), 'entries': len(entries),
            'oneWay': sum(1 for g, v, _ in entries if (v, g) not in {(x, y) for x, y, _ in entries})}
    lines = [
        '/*',
        " * GENERATED by scripts/build-fe5-supports.py from Thracia 776's supports table ($88:80CD). Do not edit by hand.",
        ' */',
        '',
        '/** What a support gives: the bonus amounts the table uses, how close the partner must be, how many entries the table has and',
        ' * how many of them go one way only. */',
        f'export const FE5_SUPPORTS = {json.dumps(data, indent=2)} as const',
    ]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(data)


if __name__ == '__main__':
    main()
