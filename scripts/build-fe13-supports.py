"""
What supports do in Fire Emblem Awakening: the dual support table (GameData's PartnerEnhanceData) and how the battle code reads it.

    python scripts/build-fe13-supports.py   ->   src/data/fe13/fe13Supports.ts

PartnerEnhanceData is 13 rows of four bytes (hit, avoid, crit, crit avoid) for a total support rank of 0 to 12. The program (code.bin,
0x218dd8) sums the rank over the allies beside the lead unit (or its pair-up partner): each counts its support level with the lead
unit plus one (0x2aee78 returns the level, none 0 to S 4, and 0x2aee80 adds 1), the Dual Support+ skill adds 4, and the total is held
below the table's length (0x219a1c: a total at or past the last row reads the last). The rows are added to the lead unit's hit, avoid,
crit and crit avoid.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fe13_data as D  # noqa: E402
from fe13_code import u32  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fe13', 'fe13Supports.ts')
# The instructions the reading above relies on, so a different dump fails here rather than giving wrong numbers.
CODE = {
    0x2AEE80: 0xE2800001,  # add r0, r0, #1: a partner's support level plus one
    0x219A10: 0x13A00004,  # movne r0, #4: Dual Support+ adds 4
    0x219A28: 0xA2410001,  # subge r0, r1, #1: a total past the table reads its last row
}


def main():
    for addr, word in CODE.items():
        assert u32(addr) == word, f'{addr:#x}: {u32(addr):#010x}'
    b = D.gamedata()
    o, n = b.at['PartnerEnhanceData'], b.u32(b.at['PartnerEnhanceDataNum'])
    rows = [[b.u8(o + 4 * i + k) for k in range(4)] for i in range(n)]
    data = {'rows': rows, 'perLevel': {'none': 1, 'C': 2, 'B': 3, 'A': 4, 'S': 5}, 'skill': 4, 'max': n - 1}
    lines = [
        '/*',
        " * GENERATED by scripts/build-fe13-supports.py from Awakening's GameData.bin (PartnerEnhanceData) and the dual support code.",
        ' * Do not edit by hand.',
        ' */',
        '',
        '/** Dual support: [hit, avoid, crit, crit avoid] for each total support rank (0 up); what each partner adds by its support level',
        ' * with the lead unit; what the Dual Support+ skill adds; and the highest total the table goes to. */',
        f'export const FE13_SUPPORTS = {json.dumps(data, indent=2)} as const',
    ]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', n, 'rows')


if __name__ == '__main__':
    main()
