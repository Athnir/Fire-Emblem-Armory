"""
What supports do in Fire Emblem Awakening: the dual support table (GameData's PartnerEnhanceData) and how the battle code reads it.

    python scripts/build-fe13-supports.py   ->   src/data/fe13/fe13Supports.ts

PartnerEnhanceData is 13 rows of four bytes (hit, avoid, crit, crit avoid) for a total support rank of 0 to 12. The program (code.bin,
0x218dd8) sums the rank over the allies at most a tile from the lead unit (0x2aee64): the four beside it and its pair-up partner on its
own tile; each counts its support level with the lead unit plus one (0x2aee78 returns the level, none 0 to S 4, and 0x2aee80 adds 1),
the Dual Support+ skill adds 4 where the total is already above 0 (0x2199b0), and the total is held below the table's length
(0x219a1c: a total at or past the last row reads the last). The rows are added to the lead unit's hit, avoid, crit and crit avoid.

Dual strikes and dual guards (0x3eeee0): the chance is the two units' Skill (a guard's: their Def, or Res against magic) added and
divided by 4, plus a step by their support level (a jump table at 0x3ef0cc), plus 10 for Dual Strike+ or Dual Guard+, held between 0
and 100. Pair-up (0x2b2c8c), for each stat but HP: the partner's stat divided by 10, 3 at most; where the partner's class gives the
stat a bonus (JobData +0x38), that bonus and (support level + 1) / 2 too; and 1 more if the lead unit has Defender (RSID_守り手).
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fe13_data as D  # noqa: E402
from fe13_code import cstr, dis, u32  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'fe13', 'fe13Supports.ts')
# The instructions the reading above relies on, so a different dump fails here rather than giving wrong numbers.
CODE = {
    0x2AEE80: 0xE2800001,  # add r0, r0, #1: a partner's support level plus one
    0x219A10: 0x13A00004,  # movne r0, #4: Dual Support+ adds 4
    0x219A28: 0xA2410001,  # subge r0, r1, #1: a total past the table reads its last row
    0x2199B4: 0xDA000018,  # ble: Dual Support+ is skipped while the total is 0
    0x2AEE68: 0xCA000007,  # bgt: a unit more than a tile away doesn't count
    0x3EEFA4: 0xE0810140,  # add r0, r1, r0, asr #2: the two units' stats added, divided by 4
    0x2B2CF8: 0xA3A03003,  # movge r3, #3: the partner's stat / 10, 3 at most
    0x2B2D38: 0xE08430A0,  # add r3, r4, r0, lsr #1: (support level + 1) / 2
    0x2B2D4C: 0x12833001,  # addne r3, r3, #1: Defender adds 1
}
# The steps by support level (none, C, B, A, S): the adds in each case of the jump table at 0x3ef0cc, strike then guard; no support
# adds to the strike only.
STEPS = {'none': (0x3EF154, None), 'C': (0x3EF0E8, 0x3EF0EC), 'B': (0x3EF104, 0x3EF108), 'A': (0x3EF120, 0x3EF124),
         'S': (0x3EF13C, 0x3EF140)}


def imm(addr):
    """The immediate an 'add rX, rY, #n' at addr adds."""
    (a, m, o), = dis(addr, 1)
    assert m == 'add' and '#' in o, (hex(addr), m, o)
    return int(o.split('#')[1], 0)


def main():
    for addr, word in CODE.items():
        assert u32(addr) == word, f'{addr:#x}: {u32(addr):#010x}'
    b = D.gamedata()
    o, n = b.at['PartnerEnhanceData'], b.u32(b.at['PartnerEnhanceDataNum'])
    rows = [[b.u8(o + 4 * i + k) for k in range(4)] for i in range(n)]
    assert cstr(0x2B2D5C) == 'RSID_守り手' and cstr(0x3EF1C0) == 'RSID_デュアルアタック＋' and cstr(0x3EF1DC) == 'RSID_デュアルガード＋'
    strike = {lv: imm(s) for lv, (s, _) in STEPS.items()}
    guard = {lv: imm(g) if g else 0 for lv, (_, g) in STEPS.items()}
    data = {'rows': rows, 'perLevel': {'none': 1, 'C': 2, 'B': 3, 'A': 4, 'S': 5}, 'skill': 4, 'max': n - 1, 'supporters': 5,
            'dualStrike': {'perLevel': strike, 'skill': imm(0x3EF044)}, 'dualGuard': {'perLevel': guard, 'skill': imm(0x3EF068)},
            'pairUp': {'statStep': 10, 'statCap': 3, 'perLevel': {lv: (k + 1) // 2 for k, lv in enumerate(strike)}, 'defender': 1}}
    lines = [
        '/*',
        " * GENERATED by scripts/build-fe13-supports.py from Awakening's GameData.bin (PartnerEnhanceData) and the dual support code.",
        ' * Do not edit by hand.',
        ' */',
        '',
        '/** Dual support: [hit, avoid, crit, crit avoid] for each total support rank (0 up); what each partner adds by its support level',
        ' * with the lead unit; what the Dual Support+ skill adds; the highest total the table goes to; how many units can count (the four',
        ' * beside the unit and its pair-up partner). Dual strikes and guards: the step each support level adds to the chance, and the',
        " * skill's. Pair-up: the partner's stat per point given (and the most), what each support level adds to a stat the partner's",
        " * class raises, and Defender's point. */",
        f'export const FE13_SUPPORTS = {json.dumps(data, indent=2)} as const',
    ]
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', n, 'rows')


if __name__ == '__main__':
    main()
